  function bindPlanDemo() {
    var input = $("#demo-capacity"), results = $("#demo-results"), status = $("#demo-status");
    function run() {
      if (!input.checkValidity()) {
        results.innerHTML = ""; results.classList.add("hidden");
        input.setAttribute("aria-invalid", "true");
        status.textContent = "请输入 0–48 之间、以 0.5 为间隔的有效工时，再运行示例。";
        input.focus(); return;
      }
      input.removeAttribute("aria-invalid");
      $("#demo-capacity-display").textContent = input.value + " 小时";
      // 所有比较都以整数分钟进行，不使用模型计算，也不改变源数据。
      var orders = [
        { id: "DEMO-01", quantity: 120, minutes: 5, available: 12 * 60 },
        { id: "DEMO-02", quantity: 180, minutes: 5, available: Number(input.value) * 60 },
        { id: "DEMO-03", quantity: 90, minutes: null, available: 8 * 60 }
      ];
      function hours(minutes) { return String(minutes / 60) + " 小时"; }
      var risk = 0, pending = 0, reminders = [];
      var rows = orders.map(function (order) {
        var required = order.minutes === null ? null : order.quantity * order.minutes;
        var gap = required === null ? null : Math.max(0, required - order.available);
        var state, next;
        if (required === null) {
          pending++; state = "待补资料"; next = "请工艺人员补充并确认单件工时";
          reminders.push(order.id + "：缺少单件工时，暂不判断交期；请工艺人员补齐。");
        } else if (gap > 0) {
          risk++; state = "工时不足，缺 " + hours(gap); next = "请计划员核实班次，提交调整建议";
          reminders.push(order.id + "：需用 " + hours(required) + "，可用 " + hours(order.available) + "，缺 " + hours(gap) + "；请计划员核实。");
        } else { state = "工时校验通过"; next = "仍需核对物料、工序等待等现场条件"; }
        return '<tr data-order="' + order.id + '"><th scope="row">' + order.id + '</th><td data-label="需用工时">' + (required === null ? "无法计算" : hours(required)) + '</td><td data-label="可用工时">' + hours(order.available) + '</td><td data-label="校验判断">' + esc(state) + '</td><td data-label="下一步">' + esc(next) + '</td></tr>';
      }).join("");
      var summary = "共检查 3 张模拟订单：" + risk + " 张工时不足，" + pending + " 张待补资料。";
      var message = "【内部订单提醒 · Demo 草稿，未发送】\n" + reminders.join("\n") + "\n请先核对现场数据，再由计划主管确认处理；本提醒不改变排产或客户交期承诺。";
      results.innerHTML = '<div class="demo-stage"><h4>2. 输出：订单风险报表</h4><p class="demo-summary" data-risk="' + risk + '" data-pending="' + pending + '">' + summary + '</p>' +
        '<div class="demo-table-wrap" tabindex="0" role="region" aria-label="模拟工时校验结果"><table class="tbl demo-report"><caption>需用工时 = 数量 × 单件工时；不足工时 = 需用工时 − 可用工时（大于零时）。</caption><thead><tr><th scope="col">订单</th><th scope="col">需用工时</th><th scope="col">可用工时</th><th scope="col">判断</th><th scope="col">下一步</th></tr></thead><tbody>' + rows + '</tbody></table></div>' +
        '<div class="demo-explanation"><b>给管理者的说明示例</b><p>' + summary + '优先核实工时不足的订单；资料不完整的订单先补数据，不能直接判成按期可交。</p></div></div>' +
        '<div class="demo-stage"><h4>3. 输出：内部群提醒草稿</h4><pre class="demo-message">' + esc(message) + '</pre><p class="demo-help">这就是审核后可发到内部群的内容示例。本页不会连接群聊，也不会发送消息。</p></div>';
      results.classList.remove("hidden"); status.textContent = "示例结果已更新，下面可查看报表与提醒草稿。";
    }
    $("#demo-run").addEventListener("click", run);
    $("#demo-reset").addEventListener("click", function () { input.value = "10"; run(); });
  }

